"""Turn the split forests (split_trees.py's mossy_glade_trees.json) and the
mesh ids the owner's import gave them into src/shared/Config/ArenaTrees.luau.

    python -I trees_to_luau.py

Mesh ids come from tree_ids.json beside this script (tree name -> asset
id), dumped from Studio after the owner imports mossy_glade_trees_roblox.glb.
A tree with no id yet is written with an empty one, and Arena.build keeps
drawing that forest as its one merged mesh until every tree has its id.

Each tree is placed exactly where it stood in the merged mesh: scaled as
the merged `Trees` part is in ArenaModels (its size over the mesh's own
bounds, per axis). The importer turns each mesh 180 degrees about Y and
Arena.build turns it back, so its offset keeps the model's own signs:
measured, mirrored offsets put ten trees into the room and these none.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
ROOT = HERE.parents[2]
OUT = ROOT / "src" / "shared" / "Config" / "ArenaTrees.luau"

#: Where ArenaModels draws each forest's merged `Trees` mesh: size, offset.
PLACED = {
    "Boss": ((74.834, 13.063, 114.270), (-0.561, 6.966, -6.824)),
    "Wide": ((96.184, 15.779, 128.239), (0.250, 8.306, -6.803)),
}


def num(v: float) -> str:
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def vec(v) -> str:
    return f"Vector3.new({num(v[0])}, {num(v[1])}, {num(v[2])})"


def main():
    manifest = json.loads((HERE / "mossy_glade_trees.json").read_text(encoding="utf-8"))
    ids_path = HERE / "tree_ids.json"
    ids = json.loads(ids_path.read_text(encoding="utf-8")) if ids_path.exists() else {}

    lines = [
        "--!strict",
        "--[[",
        "\tThe glades' forests as single trees, so each sways on its own in",
        "\tthe gusts (`Fx/ForestAmbience`; owner, 2026-10-23). GENERATED by",
        "\t`assets/models/arenas/trees_to_luau.py` from split_trees.py's",
        "\tmanifest and the owner's import: regenerate, never hand-edit.",
        "",
        "\tKeyed by `ArenaModels.ArenaPart.trees`. Each tree is placed as it",
        "\tstood in the merged mesh: `size` and `offset` from the room's centre,",
        "	and `base`, the foot of its trunk,",
        "\twhere it sways from. A forest any of whose trees has no `meshId` yet",
        "\tis drawn as its merged mesh instead.",
        "]]",
        "",
        "export type Tree = { name: string, meshId: string, size: Vector3, offset: Vector3, base: Vector3 }",
        "",
        "local ArenaTrees: { [string]: { Tree } } = {",
    ]
    missing = 0
    for forest, (part_size, part_offset) in PLACED.items():
        entry = manifest[forest]
        lo, hi = entry["bounds"]
        centre = [(a + b) / 2 for a, b in zip(lo, hi)]
        scale = [part_size[i] / (hi[i] - lo[i]) for i in range(3)]

        def place(point):
            d = [(point[i] - centre[i]) * scale[i] for i in range(3)]
            return (part_offset[0] + d[0], part_offset[1] + d[1], part_offset[2] + d[2])

        lines.append(f"\t{forest} = {{")
        for tree in entry["trees"]:
            mesh_id = ids.get(tree["name"], "")
            if not mesh_id:
                missing += 1
            size = [tree["size"][i] * scale[i] for i in range(3)]
            lines.append("\t\t{")
            lines.append(f'\t\t\tname = "{tree["name"]}",')
            lines.append(f'\t\t\tmeshId = "{mesh_id}",')
            lines.append(f"\t\t\tsize = {vec(size)},")
            lines.append(f"\t\t\toffset = {vec(place(tree['centre']))},")
            lines.append(f"\t\t\tbase = {vec(place(tree['base']))},")
            lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    lines.append("")
    lines.append("return table.freeze(ArenaTrees)")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print("wrote", OUT, "-", missing, "trees without a mesh id")


main()
