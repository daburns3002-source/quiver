"""Turn the owner's Ember Wilf rig (design_handoff_ember_wilf) into
src/shared/Config/EnemyRigs.luau.

    python -I rig_to_luau.py

Reads, beside this script:

- rig.json — the skinned mesh as Studio imported it (ember_wilf_rigged.glb
  through File -> Import 3D): its mesh and texture ids, size, and every
  bone's name, parent and rest CFrame, dumped from Studio;
- EmberWilf_Animations.rbxmx — the Run and Dash KeyframeSequences. A Pose's
  CFrame is its bone's Transform; every key is baked and Linear, so a clip
  is a list of key times and, per bone, one transform per key. Keyframes
  holding only a marker (Telegraph, Launch, Land) give the marker's time.

Each transform is written as position and quaternion (x, y, z, qx, qy, qz,
qw), rounded to five places.
"""
import json
import math
import pathlib
import xml.etree.ElementTree as ET

HERE = pathlib.Path(__file__).parent
ROOT = HERE.parents[3]
OUT = ROOT / "src" / "shared" / "Config" / "EnemyRigs.luau"
PREFIX = "Wilf_"

#: The game's wilf is the import shrunk to fit its hitbox (EnemyDesigns.Wilf).
SCALE = 0.65
#: Studs a second the Run clip is drawn at, at the import's size (the
#: handoff: "1.0 = 16 studs/s").
STRIDE_SPEED = 16


def num(v: float) -> str:
    r = round(v, 5)
    if r == 0:
        r = 0.0
    s = f"{r:.5f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def quaternion(m):
    r00, r01, r02, r10, r11, r12, r20, r21, r22 = m
    trace = r00 + r11 + r22
    if trace > 0:
        s = math.sqrt(trace + 1) * 2
        w, x, y, z = 0.25 * s, (r21 - r12) / s, (r02 - r20) / s, (r10 - r01) / s
    elif r00 > r11 and r00 > r22:
        s = math.sqrt(1 + r00 - r11 - r22) * 2
        w, x, y, z = (r21 - r12) / s, 0.25 * s, (r01 + r10) / s, (r02 + r20) / s
    elif r11 > r22:
        s = math.sqrt(1 + r11 - r00 - r22) * 2
        w, x, y, z = (r02 - r20) / s, (r01 + r10) / s, 0.25 * s, (r12 + r21) / s
    else:
        s = math.sqrt(1 + r22 - r00 - r11) * 2
        w, x, y, z = (r10 - r01) / s, (r02 + r20) / s, (r12 + r21) / s, 0.25 * s
    if w < 0:
        w, x, y, z = -w, -x, -y, -z
    return x, y, z, w


def prop(item, kind, name):
    for p in item.find("Properties"):
        if p.tag == kind and p.get("name") == name:
            return p
    return None


def cframe(pose):
    cf = prop(pose, "CoordinateFrame", "CFrame")
    v = {c.tag: float(c.text) for c in cf}
    rot = [v[k] for k in ("R00", "R01", "R02", "R10", "R11", "R12", "R20", "R21", "R22")]
    return (v["X"], v["Y"], v["Z"]) + quaternion(rot)


def poses(item, out):
    for child in item.findall("Item"):
        if child.get("class") != "Pose":
            continue
        name = prop(child, "string", "Name").text
        weight = prop(child, "float", "Weight")
        if weight is not None and float(weight.text) > 0:
            out[name] = cframe(child)
        poses(child, out)


def clip(sequence):
    keys, markers = [], {}
    for frame in sequence.findall("Item"):
        if frame.get("class") != "Keyframe":
            continue
        time = float(prop(frame, "float", "Time").text)
        for marker in frame.findall("Item"):
            if marker.get("class") == "KeyframeMarker":
                markers[prop(marker, "string", "Name").text] = time
        found = {}
        poses(frame, found)
        if found:
            keys.append((time, found))
    keys.sort(key=lambda k: k[0])
    bones = sorted({b for _, f in keys for b in f})
    loop = prop(sequence, "bool", "Loop")
    return {
        "length": keys[-1][0],
        "loop": loop is not None and loop.text == "true",
        "markers": markers,
        "times": [t for t, _ in keys],
        "bones": {b: [f.get(b, (0, 0, 0, 0, 0, 0, 1)) for _, f in keys] for b in bones},
    }


def main():
    rig = json.loads((HERE / "rig.json").read_text(encoding="utf-8"))
    tree = ET.parse(HERE / "EmberWilf_Animations.rbxmx")
    clips = {}
    for item in tree.getroot().iter("Item"):
        if item.get("class") == "KeyframeSequence":
            name = prop(item, "string", "Name").text
            clips[name.removeprefix(PREFIX)] = clip(item)

    t = "\t"
    lines = [
        "--!strict",
        "--[[",
        "\tGenerated by assets/models/enemies/ember_wilf/rig_to_luau.py from the",
        "\towner's design_handoff_ember_wilf; regenerate, never hand-edit.",
        "",
        "\tAn enemy's skinned body: the mesh part named `part` carries `bones`",
        "\t(rest CFrames at the import's size, parents first), and the game's",
        "\tbody is `scale` of that size. `clips` are its animations as each",
        "\tbone's Transform per key (x, y, z, qx, qy, qz, qw), played Linear by",
        "\t`Fx/EnemyRig`; `strideSpeed` is the studs a second Run is drawn at,",
        "\tat the import's size.",
        "]]",
        "",
        "export type Bone = { name: string, parent: string, cframe: { number } }",
        "export type Clip = {",
        "\tlength: number,",
        "\tloop: boolean,",
        "\tmarkers: { [string]: number },",
        "\ttimes: { number },",
        "\tbones: { [string]: { { number } } },",
        "}",
        "export type Rig = {",
        "\tpart: string,",
        "\tscale: number,",
        "\tstrideSpeed: number,",
        "\tbones: { Bone },",
        "\tclips: { [string]: Clip },",
        "}",
        "",
        "local EnemyRigs: { [string]: Rig } = {",
        f"{t}Wilf = {{",
        f'{t*2}part = "Body",',
        f"{t*2}scale = {num(SCALE)},",
        f"{t*2}strideSpeed = {num(STRIDE_SPEED)},",
        f"{t*2}bones = {{",
    ]
    for bone in rig["bones"]:
        cf = ", ".join(num(v) for v in bone["cframe"])
        lines.append(
            f'{t*3}{{ name = "{bone["name"]}", parent = "{bone["parent"]}", cframe = {{ {cf} }} }},'
        )
    lines.append(f"{t*2}}},")
    lines.append(f"{t*2}clips = {{")
    for name, c in clips.items():
        lines.append(f"{t*3}{name} = {{")
        lines.append(f"{t*4}length = {num(c['length'])},")
        lines.append(f"{t*4}loop = {'true' if c['loop'] else 'false'},")
        markers = ", ".join(f"{k} = {num(v)}" for k, v in sorted(c["markers"].items()))
        lines.append(f"{t*4}markers = {{ {markers} }},")
        lines.append(f"{t*4}times = {{ {', '.join(num(x) for x in c['times'])} }},")
        lines.append(f"{t*4}bones = {{")
        for bone, values in c["bones"].items():
            lines.append(f"{t*5}{bone} = {{")
            for v in values:
                lines.append(f"{t*6}{{ {', '.join(num(x) for x in v)} }},")
            lines.append(f"{t*5}}},")
        lines.append(f"{t*4}}},")
        lines.append(f"{t*3}}},")
    lines.append(f"{t*2}}},")
    lines.append(f"{t}}},")
    lines.append("}")
    lines.append("")
    lines.append("return table.freeze(EnemyRigs)")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    for name, c in clips.items():
        print(name, c["length"], c["loop"], c["markers"], len(c["times"]), len(c["bones"]))


main()
