"""Turn the Leaf Bow kit's keyframes (leaf_bow_animations.json, from Claude
Design's r15-bow-anims.js) into src/shared/Config/BowAnimations.luau.

    python -I bow_animations_to_luau.py

Regenerate after a new kit; never hand-edit the output. Each key holds the
Transform of every joint the clip moves, as a CFrame from a quaternion; the
Root also carries the clip's crouch (rootOffset). Keys ease Cubic InOut,
as the kit's KeyframeSequences do.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
OUT = HERE.parents[3] / "src" / "shared" / "Config" / "BowAnimations.luau"
clips = json.loads((HERE / "leaf_bow_animations.json").read_text())


def num(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


lines = [
    "--!strict",
    "--[[",
    "\tThe Leaf Bow's R15 animations, from the owner's Claude Design kit",
    "\t(`assets/models/weapons/leaf_bow_r15/`, 2026-10-23). GENERATED by",
    "\t`bow_animations_to_luau.py` from `leaf_bow_animations.json`:",
    "\tregenerate, never hand-edit. Played in code by `Fx/ArcherPose`.",
    "",
    "\tEach key is the Transform of every joint the clip moves; joints a clip",
    "\tleaves out stay with Roblox's own animation (Hold moves the arms only,",
    "\tso the legs still walk). Keys ease Cubic InOut. Markers are seconds",
    "\tinto the clip: Draw's `Nock` (the hand reaches the string) and Fire's",
    "\t`Release`.",
    "]]",
    "",
    "export type Key = { t: number, joints: { [string]: CFrame } }",
    "",
    "export type Clip = {",
    "\tlength: number,",
    "\tloop: boolean,",
    "\tmarkers: { [string]: number },",
    "\tkeys: { Key },",
    "}",
    "",
    "local BowAnimations: { [string]: Clip } = {",
]
for name, clip in clips.items():
    markers = {k["marker"]: k["t"] for k in clip["keys"] if k["marker"]}
    lines.append(f"\t{name} = {{")
    lines.append(f"\t\tlength = {num(clip['length'])},")
    lines.append(f"\t\tloop = {'true' if clip['loop'] else 'false'},")
    lines.append(
        "\t\tmarkers = {" + ", ".join(f"{m} = {num(t)}" for m, t in markers.items()) + "},"
    )
    lines.append("\t\tkeys = {")
    for key in clip["keys"]:
        lines.append(f"\t\t\t{{\n\t\t\t\tt = {num(key['t'])},\n\t\t\t\tjoints = {{")
        for joint in clip["joints"]:
            x, y, z, w = key["rot"][joint]
            p = key["rootOffset"] if joint == "Root" and key["rootOffset"] else [0, 0, 0]
            args = ", ".join(num(v) for v in (*p, x, y, z, w))
            lines.append(f"\t\t\t\t\t{joint} = CFrame.new({args}),")
        lines.append("\t\t\t\t},\n\t\t\t},")
    lines.append("\t\t},")
    lines.append("\t},")
lines += ["}", "", "return table.freeze(BowAnimations)", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print("wrote", OUT)
