"""Turn the weapon kits' keyframes (from Claude Design's r15-*-anims.js) into
src/shared/Config/WeaponAnimations.luau, one set of clips per weapon.

    python -I weapon_animations_to_luau.py

Regenerate after a new kit, then run StyLua on the output; never
hand-edit it. Each key holds the
Transform of every joint the clip moves, as a CFrame from a quaternion; the
Root also carries the clip's crouch (rootOffset). Keys ease Cubic InOut,
as the kit's KeyframeSequences do.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent
OUT = HERE.parents[2] / "src" / "shared" / "Config" / "WeaponAnimations.luau"
# Config/Weapons entry -> the kit's keyframes.
KITS = {
    "LeafBow": HERE / "leaf_bow_r15" / "leaf_bow_animations.json",
    "ArcaneStaff": HERE / "arcane_staff_r15" / "arcane_staff_animations.json",
    "RubyGreatsword": HERE / "ruby_greatsword_r15" / "ruby_greatsword_animations.json",
    # The Dual Bows kit, finished by leaf_bow_dual_r15/layer_clips.py.
    "LeafBowDual": HERE / "leaf_bow_dual_r15" / "leaf_bow_dual_animations.json",
    # The blocky Common skins, each with its own kit (Claude Design, 2026-10-23).
    "TwigBow": HERE / "twig_bow_r15" / "twig_bow_animations.json",
    "BranchStaff": HERE / "branch_staff_r15" / "branch_staff_animations.json",
    "TimberBlade": HERE / "timber_blade_r15" / "timber_blade_animations.json",
}


def num(v):
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


lines = [
    "--!strict",
    "--[[",
    "\tThe weapons' R15 animations, by `Config/Weapons` entry, from the",
    "\towner's Claude Design kits (`assets/models/weapons/*_r15/`,",
    "\t2026-10-23). GENERATED by",
    "\t`assets/models/weapons/weapon_animations_to_luau.py`: regenerate, never",
    "\thand-edit. Played in code by `Fx/WeaponPose`.",
    "",
    "\tEach key is the Transform of every joint the clip moves; joints a clip",
    "\tleaves out stay with Roblox's own animation (Hold moves the arms only,",
    "\tso the legs still walk). Keys ease Cubic InOut. Markers are seconds",
    "\tinto the clip: the bow's Draw `Nock` (the hand reaches the string) and",
    "\tFire `Release`, the staff's Cast `Cast`, the greatsword's slashes",
    "\t`TrailOn`, `Hit` and `TrailOff`.",
    "]]",
    "",
    "export type Key = { t: number, joints: { [string]: CFrame } }",
    "",
    "export type Clip = {",
    "\tlength: number,",
    "\tloop: boolean,",
    "\tmarkers: { [string]: number },",
    "\tkeys: { Key },",
    "}",
    "",
    "local WeaponAnimations: { [string]: { [string]: Clip } } = {",
]
for weapon, path in KITS.items():
    lines.append(f"	{weapon} = {{")
    for name, clip in json.loads(path.read_text()).items():
        markers = {k["marker"]: k["t"] for k in clip["keys"] if k["marker"]}
        lines.append(f"{name} = {{")
        lines.append(f"length = {num(clip['length'])},")
        lines.append(f"loop = {'true' if clip['loop'] else 'false'},")
        lines.append(
            "markers = {" + ", ".join(f"{m} = {num(t)}" for m, t in markers.items()) + "},"
        )
        lines.append("keys = {")
        for key in clip["keys"]:
            lines.append(f"{{ t = {num(key['t'])}, joints = {{")
            for joint in clip["joints"]:
                x, y, z, w = key["rot"][joint]
                p = key["rootOffset"] if joint == "Root" and key["rootOffset"] else [0, 0, 0]
                args = ", ".join(num(v) for v in (*p, x, y, z, w))
                lines.append(f"{joint} = CFrame.new({args}),")
            lines.append("} },")
        lines.append("},")
        lines.append("},")
    lines.append("},")
lines += ["}", "", "return table.freeze(WeaponAnimations)", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print("wrote", OUT, "- run stylua on it")
