"""Generate the Mossy Glade run's twenty rooms into src/shared/Config/Balance.luau.

    python -I tools/glade_rooms.py

For a full run-through of every class (owner, 2026-10-25: "give me 20 rooms
of mossy glade ending in king bloblin ... randomly generate the rooms how
you did with thornwood in the archero layout style ... using the kit
items"). The same rules as `tools/thornwood_rooms.py`, whose checks it
uses: Archero 2's habits (mirrored pairs, short rows, a centre piece, side
lanes, a scatter), light cover, every piece a body's width from the next
and clear of the start and the gate, and a walk from the start to the exit.

Each box is drawn by the Mossy Glade kit (`KitLayout`) by its shape: a long
one is a fallen log, a tall one a stone pillar, a squat one a tree stump,
a flat one a fern thicket (blocks walking, not arrows).

Slimes first (Moss Slimes, then Brood Slimes), the Splitter Spitter from
room 7; room 20 is a Brood Slime fight in Level 1's boss room, the Glade
Heart, and every other room is random. Seeded, so the same twenty come
out every time. King Bloblin is not here any more (owner, 2026-10-26:
"king bloblin will not appear until the end of level 10"): he is only the
last wave of Mossy Glade 1-10 (`tools/glade_levels.py`).
"""
import importlib.util
import pathlib
import random

ROOT = pathlib.Path(__file__).resolve().parents[1]
BALANCE = ROOT / "src" / "shared" / "Config" / "Balance.luau"

_spec = importlib.util.spec_from_file_location("thornwood_rooms", ROOT / "tools" / "thornwood_rooms.py")
rooms = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(rooms)

SEED = 2026_10_25_20
#: KitLayout's thresholds: under 0.6 tall is flat cover; 1.7 and up a pillar.
LOG_H, PILLAR_H, STUMP_H, THICKET_H = 2.8, 3.2, 1.5, 0.4

BEGIN = rooms.GLADE_BEGIN
END_MARK = rooms.END_MARK


def log(rng, x, z, along_x):
    length = rng.choice([7.0, 9.0, 11.0])
    return (x, z, length, LOG_H, 3.5) if along_x else (x, z, 3.5, LOG_H, length)


def stump(rng, x, z):
    s = rng.choice([3.0, 3.3, 3.75])
    return (x, z, s, STUMP_H, s)


def pillar(rng, x, z):
    s = rng.choice([2.8, 3.2])
    return (x, z, s, PILLAR_H, s)


def thicket(rng, x, z):
    w = rng.choice([3.4, 5.1, 6.8])
    return (x, z, w, THICKET_H, 3.4) if rng.random() < 0.5 else (x, z, 3.4, THICKET_H, w)


def make(rng, kind, x, z):
    if kind == "log":
        return log(rng, x, z, rng.random() < 0.7)
    if kind == "stump":
        return stump(rng, x, z)
    if kind == "pillar":
        return pillar(rng, x, z)
    return thicket(rng, x, z)


def pattern(rng):
    """One room's pieces, by one of Archero 2's habits, in the glade's kit."""
    kind = rng.choice(["pair", "row", "centre", "scatter", "pairs", "lane"])
    mirrored = rooms.mirrored
    pieces = []
    if kind == "pair":
        for _ in range(rng.choice([1, 2])):
            p = make(rng, rng.choice(["stump", "pillar", "log", "thicket"]), rng.uniform(5, 11), rng.uniform(-18, 14))
            pieces += [p, mirrored(p)]
    elif kind == "row":
        z = rng.uniform(-16, 10)
        xs = {2: [-7, 7], 3: [-10, 0, 10]}[rng.choice([2, 3])]
        k = rng.choice(["stump", "pillar", "thicket"])
        pieces = [make(rng, k, x, z) for x in xs]
    elif kind == "centre":
        pieces.append(log(rng, 0, rng.uniform(-8, 4), True))
        p = make(rng, rng.choice(["stump", "pillar"]), rng.uniform(7, 11), rng.uniform(-20, -12))
        pieces += [p, mirrored(p)]
    elif kind == "pairs":
        z = rng.uniform(-14, 6)
        p = log(rng, rng.uniform(8, 10), z, rng.random() < 0.5)
        pieces += [p, mirrored(p)]
        if rng.random() < 0.6:
            pieces.append(thicket(rng, 0, z + rng.choice([-9, 9])))
    elif kind == "lane":
        for z in rng.sample([-16, -6, 4], 2):
            p = log(rng, 11.5, z, False)
            pieces += [p, mirrored(p)]
    else:
        for _ in range(rng.randint(2, 5)):
            pieces.append(make(rng, rng.choice(["stump", "stump", "pillar", "log", "thicket"]),
                               rng.uniform(-12, 12), rng.uniform(-18, 14)))
    return kind, pieces


def roster(n):
    """Who fights in room n (1-19): a new enemy at a time, then mixes."""
    if n < 4:
        return 2 + (n > 1), "meleeCharger"
    if n < 7:
        return 3 + (n > 5), "meleeCharger, meleeCharger, broodSlime"
    if n < 10:
        return 4, "meleeCharger, broodSlime, spreadShooter"
    count = min(6, 4 + max(0, n - 10) // 3)
    mixes = [
        "meleeCharger, meleeCharger, broodSlime, spreadShooter",
        "meleeCharger, broodSlime, spreadShooter",
        "broodSlime, spreadShooter, meleeCharger",
    ]
    return count, mixes[n % len(mixes)]


def main():
    rng = random.Random(SEED)
    out = [
        BEGIN + ": twenty Mossy Glade rooms for a run-through,\n"
        "\t\tgenerated by `tools/glade_rooms.py` in Archero 2's layout style\n"
        "\t\tfrom the glade's kit (owner: \"give me 20 rooms of mossy glade\n"
        "\t\tending in king bloblin\"). Every room is random but the 20th: a\n"
        "\t\tBrood Slime fight in Level 1's boss room, the Glade Heart; King\n"
        "\t\tBloblin waits for the end of 1-10. Edit the script, not these rows.\n"
        "\t]]\n"
    ]
    kinds = []
    for n in range(1, 21):
        if n == 20:
            # Always Level 1's boss room, the Glade Heart (owner: "the king
            # bloblin fight should always be in the previously created boss
            # fight room though, the rest of the rooms can be random"), now
            # without him: he waits for the end of 1-10 (owner, 2026-10-26).
            name, arena, pieces = "Glade Heart", "GladeBoss", rooms.BOSS_ARENA
            count, who = 6, "broodSlime, broodSlime, spreadShooter"
        else:
            for _ in range(10000):
                kind, pieces = pattern(rng)
                if rooms.fits(pieces) and rooms.walkable(pieces):
                    break
            else:
                raise SystemExit(f"room {n}: no layout fits")
            kinds.append(kind)
            name, arena = f"Mossy Glade {n}", "GladeLogs"
            count, who = roster(n)
        assert rooms.walkable(pieces), name
        out.append(
            "\t{\n"
            f'\t\tname = "{name}",\n'
            f'\t\tarena = "{arena}",\n'
            + rooms.obstacles_lua(pieces)
            + f"\t\tenemyCount = {count},\n"
            f"\t\troster = {{ {who} }},\n"
            "\t},\n"
        )
    text = BALANCE.read_text(encoding="utf-8")
    j = text.index(END_MARK)
    i = text.index(BEGIN) if BEGIN in text else j + 1
    block = "".join(out).rstrip("\n")
    if BEGIN in text:
        text = text[:i] + block + text[j:]
    else:
        text = text[:j] + "\n\n" + block + text[j:]
    BALANCE.write_text(text, encoding="utf-8", newline="\n")
    print("wrote 20 rooms:", {k: kinds.count(k) for k in sorted(set(kinds))})


if __name__ == "__main__":
    main()
