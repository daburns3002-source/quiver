"""Turn the owner's Studio imports of Claude Design pets into
src/shared/Config/PetModels/<Name>.luau, so the game can rebuild each pet
from its mesh ids (the way enemy meshes are built) and play its clips.

    python -I tools/imports_to_luau.py

Reads assets/models/model_imports.json, the output of
tools/studio/dump_models.luau (one entry per imported model, named as the
importer named it, which is the GLB's file name), and
assets/models/model_clips.json, whose GLB file names say which game name
each import belongs to. Writes one module per model found in both, holding
each part's name, mesh and texture ids, colour, material, transparency,
size and place relative to the model's pivot.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
DUMP = ROOT / "assets" / "models" / "model_imports.json"
MANIFEST = ROOT / "assets" / "models" / "model_clips.json"
OUT = ROOT / "src" / "shared" / "Config" / "PetModels"


def num(v: float) -> str:
    r = round(float(v), 5)
    if r == 0:
        return "0"
    return f"{r:.5f}".rstrip("0").rstrip(".")


def nums(vs) -> str:
    return "{ " + ", ".join(num(v) for v in vs) + " }"


def lua_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    dump = json.loads(DUMP.read_text(encoding="utf-8"))
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    by_stem = {
        pathlib.Path(rel).stem.lower(): key for key, rel in manifest.items() if not key.startswith("_")
    }
    OUT.mkdir(parents=True, exist_ok=True)
    written = set()
    for model_name, model in dump.items():
        key = by_stem.get(model_name.lower())
        if not key:
            print(f"skipped {model_name}: not in model_clips.json")
            continue
        lines = [
            "--!strict",
            "--[[",
            f"\t{key} as the owner imported it ({model_name}). Generated by",
            "\ttools/imports_to_luau.py from tools/studio/dump_models.luau's output;",
            "\tregenerate after a re-import, never hand-edit.",
            "",
            "\tEach part: its name (the GLB node's, which Config/ModelClips keys on),",
            "\tmesh and texture ids, colour, material, transparency, size, and its",
            "\tplace relative to the model's pivot (12 CFrame components).",
            "]]",
            "",
            "return table.freeze({",
        ]
        for p in model["parts"]:
            lines.append(
                "\t{ "
                + f"name = {lua_string(p['name'])}, meshId = {lua_string(p['meshId'])}, "
                + f"textureId = {lua_string(p.get('textureId') or '')}, color = {nums(p['color'])}, "
                + f"material = {lua_string(p['material'])}, transparency = {num(p['transparency'])}, "
                + f"size = {nums(p['size'])}, cframe = {nums(p['cframe'])}"
                + " },"
            )
        lines += ["})", ""]
        path = OUT / f"{key}.luau"
        path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
        written.add(path.name)
        print(f"{key}: {len(model['parts'])} parts from {model_name}")
    for old in OUT.glob("*.luau"):
        if old.name not in written:
            old.unlink()
            print(f"removed {old.name}")


if __name__ == "__main__":
    main()
