"""Writes src/shared/Config/PlayerModels from the split rigs and their Studio ids.

    python tools/player_rigs/rigs_to_luau.py

Reads `assets/models/players/<name>_r15.json` (from `split_r15.py`) and
`assets/models/players/mesh_ids.txt` (from `tools/studio/dump_player_rigs.luau`
run after the owner's Import 3D of the `_r15.glb` files: one
`name/Piece|meshId|textureId` line per piece). A rig with any piece not yet
uploaded is written with `uploaded = false` and empty ids, and the game keeps
the player's own avatar for it (`Run/PlayerBody`).

Scales the 0.98 m Tripo models to SCALE studs a metre, about the height of a
default R15 body, so held weapons and the camera still fit.
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
RIGS = os.path.join(ROOT, "assets", "models", "players")
OUT = os.path.join(ROOT, "src", "shared", "Config", "PlayerModels")
SCALE = 5.4
HRP_HEIGHT = 2  # a default R15 HumanoidRootPart

NAMES = [
    "ranger_male", "ranger_female", "arcanist_male", "arcanist_female",
    "warden_male", "warden_female", "assassin_male", "assassin_female",
]
R15 = [
    "LowerTorso", "UpperTorso", "Head",
    "LeftUpperArm", "LeftLowerArm", "LeftHand", "RightUpperArm", "RightLowerArm", "RightHand",
    "LeftUpperLeg", "LeftLowerLeg", "LeftFoot", "RightUpperLeg", "RightLowerLeg", "RightFoot",
]
# joint: (parent part, child part)
JOINTS = {
    "Root": ("HumanoidRootPart", "LowerTorso"),
    "Waist": ("LowerTorso", "UpperTorso"),
    "Neck": ("UpperTorso", "Head"),
}
for side in ("Left", "Right"):
    JOINTS[side + "Shoulder"] = ("UpperTorso", side + "UpperArm")
    JOINTS[side + "Elbow"] = (side + "UpperArm", side + "LowerArm")
    JOINTS[side + "Wrist"] = (side + "LowerArm", side + "Hand")
    JOINTS[side + "Hip"] = ("LowerTorso", side + "UpperLeg")
    JOINTS[side + "Knee"] = (side + "UpperLeg", side + "LowerLeg")
    JOINTS[side + "Ankle"] = (side + "LowerLeg", side + "Foot")


def module_name(name):
    cls, look = name.split("_")
    return cls.capitalize() + look.capitalize()


def num(v):
    return f"{v:.4f}".rstrip("0").rstrip(".") if abs(v) > 5e-5 else "0"


def vec(v):
    return "{ " + ", ".join(num(x) for x in v) + " }"


def read_ids():
    ids = {}
    path = os.path.join(RIGS, "mesh_ids.txt")
    if os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            key, mesh, tex = (line.split("|") + ["", ""])[:3]
            ids[key] = (mesh, tex)
    return ids


def write(name, ids):
    rig = json.load(open(os.path.join(RIGS, name + "_r15.json")))
    root = rig["joints"]["Root"]

    def rel(p):
        return [(p[i] - root[i]) * SCALE for i in range(3)]

    pieces = R15 + sorted(rig["accessories"])
    uploaded = all(ids.get(f"{name}/{p}", ("", ""))[0] for p in pieces)
    cls, look = name.split("_")
    out = [
        "--!strict",
        "--[[",
        f"\t{cls.capitalize()} ({look}) as an R15 body: the owner's Tripo model",
        f"\t(`assets/concepts/blocky/players/tripo/low/{name}.glb`) split into the",
        "\t15 R15 parts and its accessories by `tools/player_rigs/split_r15.py`.",
        "\tGenerated by `tools/player_rigs/rigs_to_luau.py` from",
        f"\t`assets/models/players/{name}_r15.json` and the Studio mesh ids; never",
        "\thand-edit.",
        "",
        "\tStuds, relative to the Root joint (the HumanoidRootPart's centre),",
        "\tfacing -Z. `joints` are the R15 rig attachments' places; each part's",
        "\t`position` is its centre. Accessories hang off `parent`.",
        "]]",
        "",
        "return table.freeze({",
        f'\tclass = "{cls.capitalize()}",',
        f'\tlook = "{look}",',
        f"\tuploaded = {'true' if uploaded else 'false'},",
        f"\thipHeight = {num(root[1] * SCALE - HRP_HEIGHT / 2)},",
        f"\theight = {num(rig['height'] * SCALE)},",
        "\tparts = table.freeze({",
    ]

    def piece(p, parent=None):
        part = rig["parts"][p]
        mesh, tex = ids.get(f"{name}/{p}", ("", "")) if uploaded else ("", "")
        lines = ["\t\ttable.freeze({", f'\t\t\tname = "{p}",']
        if parent:
            lines.append(f'\t\t\tparent = "{parent}",')
        lines += [
            f'\t\t\tmeshId = "{mesh}",',
            f'\t\t\ttextureId = "{tex}",',
            f"\t\t\tsize = {vec([s * SCALE for s in part['size']])},",
            f"\t\t\tposition = {vec(rel(part['centre']))},",
            "\t\t}),",
        ]
        return lines

    for p in R15:
        out += piece(p)
    out += ["\t}),", "\taccessories = table.freeze({"]
    for acc, parent in sorted(rig["accessories"].items()):
        out += piece(acc, parent)
    out += ["\t}),", "\tjoints = table.freeze({"]
    for j in JOINTS:
        out.append(f"\t\t{j} = {vec(rel(rig['joints'][j]))},")
    out += ["\t}),", "})", ""]
    with open(os.path.join(OUT, module_name(name) + ".luau"), "w", newline="\n") as f:
        f.write("\n".join(out))
    return uploaded


def main():
    os.makedirs(OUT, exist_ok=True)
    ids = read_ids()
    for name in NAMES:
        print(name, "uploaded" if write(name, ids) else "waiting for the Studio import")


if __name__ == "__main__":
    main()
